#!/bin/bash
# setup-notifications.sh — install/refresh Claude Code notification plumbing.
#
# Usage:
#   setup-notifications.sh [CONFIG_DIR]
#
#   CONFIG_DIR  Path to the Claude config directory containing settings.json.
#               Defaults to $CLAUDE_CONFIG_DIR if set, else ~/.claude.
#               Run once per directory to wire up notifications for that
#               Claude install (e.g. a work-specific ~/SupplyTrace/src/claude-config).
#
# What it does:
#   1. Preflight     — verifies ghostty / tmux / jq / terminal-notifier exist;
#                      installs terminal-notifier via brew if missing.
#   2. paths.env     — resolves absolute binary paths once and writes them to
#                      bin/paths.env so notify.sh and ghostty-focus.sh don't
#                      need to hardcode /opt/homebrew/... (keeps the dotfiles
#                      portable across Apple Silicon / Intel Macs).
#   3. chmod +x      — ensures notify.sh and ghostty-focus.sh are executable
#                      on every machine (git doesn't always preserve this).
#   4. settings.json — wires notify.sh into the "needs you" Notification
#                      matchers (and out of Stop / SubagentStop) in
#                      <CONFIG_DIR>/settings.json via jq, backing up the
#                      original to settings.json.bak.<timestamp> first.
#   5. Permission    — triggers macOS notification-permission dialog once so
#                      the first real notification isn't silently dropped.
#   6. Verify        — prints a next-steps checklist.
#
# Safe to re-run: every step checks state before acting. Idempotent.
#
# To uninstall: restore <CONFIG_DIR>/settings.json from the most recent
# settings.json.bak.<timestamp>, then `rm bin/paths.env`.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PATHS_ENV="$SCRIPT_DIR/paths.env"

# Resolve target config directory: CLI arg > $CLAUDE_CONFIG_DIR > ~/.claude.
CONFIG_DIR="${1:-${CLAUDE_CONFIG_DIR:-$HOME/.claude}}"
# Expand a leading ~ if passed literally on the command line.
CONFIG_DIR="${CONFIG_DIR/#\~/$HOME}"
SETTINGS_FILE="$CONFIG_DIR/settings.json"

log()  { printf '==> %s\n' "$*"; }
warn() { printf '!!  %s\n' "$*" >&2; }
die()  { warn "$*"; exit 1; }

# --- Step 1: Preflight --------------------------------------------------------

log "Step 1/6: preflight — checking required tools"

require_brew_install() {
  local bin="$1" pkg="$2"
  if ! command -v "$bin" >/dev/null 2>&1; then
    die "$bin not found. Install with: brew install $pkg"
  fi
}

# Fatal if missing — too heavy to auto-install.
require_brew_install jq jq
require_brew_install tmux tmux
# Ghostty is checked by existence rather than PATH since it's a .app, but
# the osascript activation below covers that path too.
command -v ghostty >/dev/null 2>&1 || warn "ghostty not on PATH — click-to-focus will still work via osascript, but double-check this is intentional."

# terminal-notifier is light enough to auto-install.
if ! command -v terminal-notifier >/dev/null 2>&1; then
  log "terminal-notifier missing — installing via brew"
  brew install terminal-notifier
fi

# --- Step 2: Resolve paths ----------------------------------------------------

log "Step 2/6: resolving absolute paths into $PATHS_ENV"

JQ_BIN=$(command -v jq)
TMUX_BIN=$(command -v tmux)
NOTIFIER_BIN=$(command -v terminal-notifier)
OSASCRIPT_BIN=$(command -v osascript)

cat > "$PATHS_ENV" <<EOF
# Generated by setup-notifications.sh. Machine-specific; do not commit.
# Regenerate by re-running setup-notifications.sh.
JQ="$JQ_BIN"
TMUX_BIN="$TMUX_BIN"
NOTIFIER="$NOTIFIER_BIN"
OSASCRIPT="$OSASCRIPT_BIN"
EOF

log "  JQ=$JQ_BIN"
log "  TMUX_BIN=$TMUX_BIN"
log "  NOTIFIER=$NOTIFIER_BIN"
log "  OSASCRIPT=$OSASCRIPT_BIN"

# --- Step 3: Ensure scripts are executable -----------------------------------

log "Step 3/6: ensuring notify.sh and ghostty-focus.sh are executable"
chmod +x "$SCRIPT_DIR/notify.sh" "$SCRIPT_DIR/ghostty-focus.sh"

# --- Step 4: Merge settings.json ---------------------------------------------

log "Step 4/6: merging hooks into $SETTINGS_FILE"

if [[ ! -d "$CONFIG_DIR" ]]; then
  die "Config directory $CONFIG_DIR does not exist. Pass a valid path, or unset CLAUDE_CONFIG_DIR."
fi
if [[ ! -f "$SETTINGS_FILE" ]]; then
  die "$SETTINGS_FILE does not exist — run Claude Code against $CONFIG_DIR at least once first."
fi

BACKUP="$SETTINGS_FILE.bak.$(date +%Y%m%d-%H%M%S)"
cp "$SETTINGS_FILE" "$BACKUP"
log "  backup: $BACKUP"

NOTIFY_CMD="\$HOME/src/dotfiles/claude/bin/notify.sh"

# Notify only when a session is blocked on the user: a permission prompt, an
# MCP elicitation form, or ~60s idle after a turn ends (idle_prompt, which
# self-debounces background-agent wakeups). notify.sh goes first in each of
# those Notification matchers; other hooks there (e.g. tmux-state.sh) are kept.
# notify.sh is stripped from Stop / SubagentStop — every turn and subagent end
# was too noisy — and Claude Code's built-in channel is disabled so Ghostty
# doesn't post a duplicate banner.
TMP_OUT=$(mktemp)
"$JQ_BIN" --arg cmd "$NOTIFY_CMD" '
  def notify_hook: { type: "command", command: $cmd };
  def is_notify: (.command // "") | contains("notify.sh");
  def strip_notify:
    map(.hooks = ((.hooks // []) | map(select(is_notify | not))))
    | map(select((.hooks | length) > 0));
  def ensure_notify($m):
    if any(.[]; .matcher == $m)
    then map(if .matcher == $m
             then .hooks = ([notify_hook] + ((.hooks // []) | map(select(is_notify | not))))
             else . end)
    else . + [{ matcher: $m, hooks: [notify_hook] }]
    end;

  .hooks = (.hooks // {})
  | .hooks.Notification = ((.hooks.Notification // [])
      | ensure_notify("permission_prompt")
      | ensure_notify("idle_prompt")
      | ensure_notify("elicitation_dialog"))
  | .hooks.Stop = ((.hooks.Stop // []) | strip_notify)
  | .hooks.SubagentStop = ((.hooks.SubagentStop // []) | strip_notify)
  | if .hooks.Stop == [] then del(.hooks.Stop) else . end
  | if .hooks.SubagentStop == [] then del(.hooks.SubagentStop) else . end
  | .preferredNotifChannel = "notifications_disabled"
' "$SETTINGS_FILE" > "$TMP_OUT"

mv "$TMP_OUT" "$SETTINGS_FILE"
log "  settings.json updated (original preserved at $BACKUP)"

# --- Step 5: Prime macOS notification permission ------------------------------

log "Step 5/6: firing a test notification to prompt for macOS permission"
"$NOTIFIER_BIN" -title "Claude Code setup" -message "Notifications are wired up." -sound Glass >/dev/null 2>&1 || true

# --- Step 6: Verification checklist -------------------------------------------

cat <<'EOF'

==> Step 6/6: setup complete. Next steps:

  1. In a running Claude Code session, run:   /hooks
     Confirm the Notification matchers (permission_prompt, idle_prompt,
     elicitation_dialog) point at notify.sh, and Stop / SubagentStop
     do not.

  2. Trigger a permission prompt and listen for Glass. Then have
     Claude ask a question, walk away, and confirm a banner arrives
     within ~60s (idle_prompt).

  3. Click a notification from another app — Ghostty should
     foreground and the correct tmux pane should be selected.

  4. If the Notification payload field names differ from what
     notify.sh assumes, capture a real payload by temporarily
     setting a hook command to:
        cat >> ~/claude-hook-payloads.jsonl
     inspect the JSON, and adjust notify.sh accordingly.

EOF
